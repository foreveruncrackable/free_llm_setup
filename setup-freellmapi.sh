#!/usr/bin/env bash
# =============================================================================
# FreeLLMAPI — full from-scratch setup & connect script
# =============================================================================
# What this does:
#   1. Checks Docker + openssl
#   2. Creates ~/freellmapi (or $FREELLMAPI_DIR)
#   3. Generates ENCRYPTION_KEY + .env (keeps existing key on re-run)
#   4. Writes docker-compose.yml
#   5. Pulls image and starts the container
#   6. Waits until the API is up
#   7. Prints dashboard URL, setup-code hint, and all connection steps
#
# Usage:
#   chmod +x setup-freellmapi.sh
#   ./setup-freellmapi.sh
#
# Optional env overrides:
#   FREELLMAPI_DIR=~/my-api   PORT=3001   HOST_BIND=127.0.0.1
#   HOST_BIND=0.0.0.0         # allow LAN access (trusted network only)
# =============================================================================

set -euo pipefail

# ---------- Config ----------
FREELLMAPI_DIR="${FREELLMAPI_DIR:-$HOME/freellmapi}"
PORT="${PORT:-3001}"
HOST_BIND="${HOST_BIND:-127.0.0.1}"
IMAGE="ghcr.io/tashfeenahmed/freellmapi:latest"
BASE_URL="http://localhost:${PORT}"
API_URL="${BASE_URL}/v1"

# ---------- Colors ----------
red()    { printf '\033[0;31m%s\033[0m\n' "$*"; }
green()  { printf '\033[0;32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[0;33m%s\033[0m\n' "$*"; }
blue()   { printf '\033[0;34m%s\033[0m\n' "$*"; }
bold()   { printf '\033[1m%s\033[0m\n' "$*"; }

need_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    red "ERROR: required command not found: $1"
    case "$1" in
      docker)
        echo "  Install Docker: https://docs.docker.com/get-docker/"
        echo "  On Linux also install the Compose plugin."
        ;;
      openssl) echo "  Install openssl (usually already present)." ;;
    esac
    exit 1
  fi
}

# ---------- Banner ----------
echo
bold "=============================================="
bold "  FreeLLMAPI — from-scratch setup"
bold "=============================================="
echo

# ---------- Pre-flight ----------
blue "[1/6] Checking prerequisites..."
need_cmd docker
need_cmd openssl

if ! docker info >/dev/null 2>&1; then
  red "ERROR: Docker daemon is not running."
  echo "  Start Docker Desktop (macOS/Windows) or: sudo systemctl start docker"
  exit 1
fi

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE=(docker-compose)
else
  red "ERROR: neither 'docker compose' nor 'docker-compose' found."
  exit 1
fi
green "  Docker OK — using: ${COMPOSE[*]}"

# ---------- Directory ----------
blue "[2/6] Preparing install directory: $FREELLMAPI_DIR"
mkdir -p "$FREELLMAPI_DIR"
cd "$FREELLMAPI_DIR"

# ---------- .env ----------
blue "[3/6] Encryption key & .env"
if [[ ! -f .env ]]; then
  ENCRYPTION_KEY="$(openssl rand -hex 32)"
  cat > .env <<EOF
# FreeLLMAPI — generated by setup-freellmapi.sh
ENCRYPTION_KEY=$ENCRYPTION_KEY
PORT=$PORT
HOST_BIND=$HOST_BIND
EOF
  green "  Created .env with new ENCRYPTION_KEY"
else
  green "  Existing .env kept (ENCRYPTION_KEY not changed)"
  grep -q '^PORT=' .env      || echo "PORT=$PORT" >> .env
  grep -q '^HOST_BIND=' .env || echo "HOST_BIND=$HOST_BIND" >> .env
fi

# ---------- docker-compose.yml ----------
blue "[4/6] docker-compose.yml"
cat > docker-compose.yml <<EOF
# FreeLLMAPI — generated by setup-freellmapi.sh
services:
  freellmapi:
    image: ${IMAGE}
    container_name: freellmapi
    restart: unless-stopped
    ports:
      - "\${HOST_BIND:-127.0.0.1}:\${PORT:-3001}:3001"
    env_file:
      - .env
    volumes:
      - freellmapi-data:/app/server/data
    environment:
      - NODE_ENV=production
      - PORT=3001
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3001/').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 15s

volumes:
  freellmapi-data:
EOF
green "  docker-compose.yml written"

# ---------- Pull & start ----------
blue "[5/6] Pulling image and starting container..."
"${COMPOSE[@]}" pull
"${COMPOSE[@]}" up -d

# ---------- Wait for healthy ----------
blue "[6/6] Waiting for FreeLLMAPI to become ready..."
READY=0
for i in $(seq 1 30); do
  if curl -sf -o /dev/null --max-time 2 "${BASE_URL}/" 2>/dev/null; then
    READY=1
    break
  fi
  # fallback: check container is running
  if ! docker ps --format '{{.Names}}' | grep -qx freellmapi; then
    red "  Container stopped unexpectedly. Logs:"
    "${COMPOSE[@]}" logs --tail 40 freellmapi || true
    exit 1
  fi
  printf "  still starting... (%ds)\n" "$((i * 2))"
  sleep 2
done

if [[ "$READY" -ne 1 ]]; then
  yellow "  Timed out waiting for HTTP. Container may still be starting."
  yellow "  Check logs:  cd $FREELLMAPI_DIR && ${COMPOSE[*]} logs -f freellmapi"
else
  green "  FreeLLMAPI is up"
fi

# ---------- Setup code from logs (if first run) ----------
echo
yellow "---- First-run setup code (only needed from another device) ----"
SETUP_CODE_LINE="$("${COMPOSE[@]}" logs freellmapi 2>/dev/null | grep -i 'First-run setup code:' | tail -1 || true)"
if [[ -n "$SETUP_CODE_LINE" ]]; then
  echo "$SETUP_CODE_LINE"
  echo "  (A browser on THIS machine does not need the code.)"
else
  echo "  No setup code in logs (account may already exist, or still booting)."
  echo "  Re-check with:  cd $FREELLMAPI_DIR && ${COMPOSE[*]} logs freellmapi | grep -i setup"
fi

# ---------- Success summary ----------
echo
bold "=============================================="
green "  SETUP COMPLETE"
bold "=============================================="
echo
bold "URLs"
echo "  Dashboard:  ${BASE_URL}"
echo "  API base:   ${API_URL}"
echo "  Install dir: $FREELLMAPI_DIR"
echo
bold "STEP A — Create dashboard account + add provider keys"
echo "  1. Open ${BASE_URL} in your browser"
echo "  2. Create the first admin account (email + password)"
echo "  3. Go to Keys → add free keys (Groq, Google AI Studio, Cerebras, etc.)"
echo "  4. Copy the unified key from the Keys page header (starts with freellmapi-...)"
echo
bold "STEP B — Test the API (replace YOUR_KEY)"
cat <<EOF
  curl ${API_URL}/chat/completions \\
    -H "Authorization: Bearer freellmapi-YOUR_KEY" \\
    -H "Content-Type: application/json" \\
    -d '{
      "model": "auto",
      "messages": [{"role": "user", "content": "Say hello in one sentence."}]
    }'
EOF
echo
bold "STEP C — Connect coding agents (after you have the unified key)"
echo "  Export once:"
echo "    export FREELLMAPI_URL=${BASE_URL}"
echo "    export FREELLMAPI_API_KEY=freellmapi-YOUR_KEY"
echo
echo "  Then run any of these (Node 20+ required for npx):"
echo "    npx freellmapi setup-claude   --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
echo "    npx freellmapi setup-codex    --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
echo "    npx freellmapi setup-cline    --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
 ho "    npx freellmapi setup-continue --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
ho "    npx freellmapi setup-aider    --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
echo "    npx freellmapi setup-opencode --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
echo "    npx freellmapi setup-cursor   --url \$FREELLMAPI_URL --api-key \$FREELLMAPI_API_KEY"
echo "    npx freellmapi list           # show all supported agents"
echo
bold "Any OpenAI-compatible client"
echo "  base_url = ${API_URL}"
echo "  api_key  = freellmapi-YOUR_KEY"
echo "  model    = auto   (or auto:fast / auto:smart / a specific model id)"
echo
bold "Useful commands"
echo "  Logs:     cd $FREELLMAPI_DIR && ${COMPOSE[*]} logs -f freellmapi"
echo "  Stop:     cd $FREELLMAPI_DIR && ${COMPOSE[*]} down"
echo "  Restart:  cd $FREELLMAPI_DIR && ${COMPOSE[*]} restart"
echo "  Update:   cd $FREELLMAPI_DIR && ${COMPOSE[*]} pull && ${COMPOSE[*]} up -d"
echo "  Uninstall (keeps data volume unless -v):"
echo "            cd $FREELLMAPI_DIR && ${COMPOSE[*]} down -v"
echo
yellow "Note: Provider API keys must be added by you in the dashboard."
yellow "This script cannot add them — they never leave your machine."
echo
